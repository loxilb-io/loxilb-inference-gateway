/*
 * ai_kv_trtllm_source_test.go — unit coverage for the TensorRT-LLM HTTP
 * event poller and its token re-hash decoder.
 *
 * The stored-event fixtures are VERBATIM live captures from a converged
 * tensorrt_llm 1.3.0rc24 fleet (Qwen2.5-7B-Instruct, tokens_per_block=32),
 * including the engine's restart signature: after an engine restart the
 * first drain returns [], then the stream restarts at event_id 0 with a
 * created event followed by fresh stored events. Regenerate against a live
 * endpoint whenever the pinned engine version moves.
 *
 * The re-hash golden vectors mirror the C-side committed constants for the
 * shared raw chained-SHA256 contract (test_kv_exact.c, generated by
 * scripts/compute_sglang_hash_refs.py) — the Go event decoder and the C
 * request pager must compute the identical digests or Tier-1.5 silently
 * never intersects.
 */

