// TestTrtllmBlockCleanGates: extra-id tokens, cache salt and multimodal
// keys make a block irreproducible by the request-side hash — never indexed.
func TestTrtllmBlockCleanGates(t *testing.T) {
	clean := func(raw string) bool {
		t.Helper()
		var blk trtllmStoredBlock
		dec := json.NewDecoder(strings.NewReader(raw))
		dec.UseNumber()
		if err := dec.Decode(&blk); err != nil {
			t.Fatalf("block decode: %v", err)
		}
		return kvTrtllmBlockClean(&blk)
	}
	if !clean(`{"tokens": [{"token_id": 1, "token_extra_id": 0}], "cache_salt": null, "mm_keys": []}`) {
		t.Error("plain block must be clean")
	}
	if clean(`{"tokens": [{"token_id": 1, "token_extra_id": 7}], "cache_salt": null, "mm_keys": []}`) {
		t.Error("extra-id token must not be clean")
	}
	if clean(`{"tokens": [{"token_id": 1, "token_extra_id": 0}], "cache_salt": "s", "mm_keys": []}`) {
		t.Error("salted block must not be clean")
	}
	if clean(`{"tokens": [{"token_id": 1, "token_extra_id": 0}], "cache_salt": null, "mm_keys": [1]}`) {
		t.Error("multimodal block must not be clean")
	}
}

// TestTrtllmPollerHTTP drives the poller against a scripted drain: an idle
// [] (backoff), then the live-captured restart pair, then a failing drain.
// The synthesized message stream must carry the engine's event_ids as seqs
// so the subscriber loop's regression/gap machinery sees the wire truth,
// and a failing poll must surface as a Recv error (the loop's rebuild path).
func TestTrtllmPollerHTTP(t *testing.T) {
	var call atomic.Int64
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Method != http.MethodPost || r.URL.Path != "/kv_cache_events" {
			t.Errorf("unexpected request %s %s", r.Method, r.URL.Path)
		}
		switch call.Add(1) {
		case 1:
			w.Write([]byte(`[]`)) // idle drain — poller backs off and retries
		case 2:
			w.Write([]byte("[" + trtllmFixtureCreated + "," + trtllmFixtureStoredFull + "]"))
		default:
			w.WriteHeader(http.StatusInternalServerError)
		}
	}))
	defer srv.Close()

	p := newTrtllmEventPoller(context.Background(), srv.Listener.Addr().String(), 32)
	if err := p.Connect(srv.Listener.Addr().String()); err != nil {
		t.Fatalf("connect: %v", err)
	}

	frames, err := p.RecvMultipart()
	if err != nil {
		t.Fatalf("recv 1: %v", err)
	}
	seq, events := decodeTrtllmFrames(t, frames)
	if seq != 0 || len(events) != 1 || events[0].Type != kvEventAllBlocksCleared {
		t.Fatalf("msg 1: seq=%d events=%+v, want created→AllBlocksCleared@0", seq, events)
	}

	frames, err = p.RecvMultipart()
	if err != nil {
		t.Fatalf("recv 2: %v", err)
	}
	seq, events = decodeTrtllmFrames(t, frames)
	if seq != 5 || len(events) != 1 || events[0].Type != kvEventBlockStored {
		t.Fatalf("msg 2: seq=%d events=%+v, want BlockStored@5", seq, events)
	}

	if _, err = p.RecvMultipart(); err == nil {
		t.Fatal("failing drain must surface as a Recv error")
	}

	// Close/Connect re-arm (the loop's rebuild path drives exactly this).
	if err := p.Close(); err != nil {
		t.Fatalf("close: %v", err)
	}
	if _, err := p.RecvMultipart(); err == nil {
		t.Fatal("closed poller must not deliver")
	}
	if err := p.Connect(srv.Listener.Addr().String()); err != nil {
		t.Fatalf("reconnect: %v", err)
	}
	done := make(chan error, 1)
	go func() {
		_, err := p.RecvMultipart()
		done <- err
	}()
	select {
	case err := <-done:
		if err == nil {
			t.Fatal("re-armed poller against the failing drain: want error")
		}
	case <-time.After(5 * time.Second):
		t.Fatal("re-armed poller wedged")
	}
}
