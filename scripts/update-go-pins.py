#!/usr/bin/env python3
"""Update or check the generated mirrors of build/go-dependencies.json.

Dockerfiles keep ordinary literals so existing small/offline fixture build
contexts continue to work. This manifest and updater own those literals;
--check rejects drift, including new unmanaged x/net or gRPC recipes.
"""
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import shlex
import subprocess
import sys
import tempfile

MANIFEST = "build/go-dependencies.json"
HEADER = "# Go dependency pins are generated by scripts/update-go-pins.py; edit build/go-dependencies.json.\n"
GOBGP = {"Dockerfile": "default", "Dockerfile.u24": "default",
         "Dockerfile.u20": "legacy", "Dockerfile.buildcheck": "legacy"}
GRPC = ["cicd/common/grpc/Dockerfile." + role
        for role in ("client", "server", "http-client", "http-server")]
SHARED_VENDOR_BUILDS = {
    "cicd/ai-json-parser/Dockerfile.mock": "json-parser-mock",
    "cicd/edge-cloud-security/backend/Dockerfile": "edge-cloud-backend",
}
GO_ONLY = ["Dockerfile.aictrl", "Dockerfile.kv-agent", "packaging/Dockerfile.build",
           "cicd/common/reflect-echo/Dockerfile", *SHARED_VENDOR_BUILDS]
RECIPES = list(GOBGP) + GRPC + GO_ONLY
MODULES = ["go.mod", "cicd/common/reflect-echo/go.mod"]
VERSION = re.compile(r"v\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?\Z")


def validate(pins):
    keys = {"schema_version", "go", "x_net", "grpc", "gobgp", "protoc_gen_go",
            "protoc_gen_go_grpc", "govulncheck"}
    if not isinstance(pins, dict) or set(pins) != keys or pins["schema_version"] != 1:
        raise ValueError("unsupported Go dependency manifest schema")
    if not isinstance(pins["go"], str) or not re.fullmatch(r"1\.\d+\.\d+", pins["go"]):
        raise ValueError("go must be a complete 1.x.y toolchain version")
    for key, profiles in [("gobgp", {"default", "legacy"})]:
        if not isinstance(pins[key], dict) or set(pins[key]) != profiles:
            raise ValueError(f"unexpected {key} profiles")
    versions = [pins[k] for k in ["x_net", "grpc", "protoc_gen_go", "protoc_gen_go_grpc", "govulncheck"]]
    versions += list(pins["gobgp"].values())
    if any(not isinstance(v, str) or not VERSION.fullmatch(v) for v in versions):
        raise ValueError("module versions must be explicit semantic versions")
    if any(not v.startswith("v3.") for v in pins["gobgp"].values()):
        raise ValueError("GoBGP v3 import paths require v3 versions")
    return pins


def replace_required(text, pattern, replacement, name):
    result, count = re.subn(pattern, replacement, text)
    if not count:
        raise ValueError(f"missing expected {name} build pin")
    return result


def render_recipe(path, text, pins):
    if path in GOBGP:
        profile = GOBGP[path]
        text = replace_required(text, r"(--branch )v[^\s]+(?= https://github\.com/osrg/gobgp\.git)",
                                lambda m: m[1] + pins["gobgp"][profile], path)
        text = replace_required(text, r"google\.golang\.org/grpc@v[^\s;&]+",
                                "google.golang.org/grpc@" + pins["grpc"], path)
    if path in GRPC:
        text = replace_required(text, r"google\.golang\.org/grpc(?:/credentials(?:/insecure)?)?@v[^\s;&]+",
                                lambda m: m[0].split("@")[0] + "@" + pins["grpc"], path)
        text = replace_required(text, r"google\.golang\.org/protobuf/cmd/protoc-gen-go@v[^\s;&]+",
                                "google.golang.org/protobuf/cmd/protoc-gen-go@" + pins["protoc_gen_go"], path)
        text = replace_required(text, r"google\.golang\.org/grpc/cmd/protoc-gen-go-grpc@v[^\s;&]+",
                                "google.golang.org/grpc/cmd/protoc-gen-go-grpc@" + pins["protoc_gen_go_grpc"], path)
    if path in GOBGP or path in GRPC:
        text = replace_required(text, r"golang\.org/x/net@v[^\s;&]+",
                                "golang.org/x/net@" + pins["x_net"], path)
    if "FROM golang:" in text:
        text = replace_required(text, r"(FROM golang:)1\.\d+(?:\.\d+)?(-alpine)?",
                                lambda m: m[1] + pins["go"] + (m[2] or ""), path)
    elif "ARG GO_VERSION=" in text:
        text = replace_required(text, r"(?m)^ARG GO_VERSION=1\.\d+\.\d+$",
                                "ARG GO_VERSION=" + pins["go"], path)
    else:
        text = replace_required(text, r"go1\.\d+\.\d+(?=\.linux-)", "go" + pins["go"], path)
    if not text.startswith(HEADER):
        text = HEADER + text
    return text


def requirement(text, module):
    found = re.findall(r"(?m)^\s*(?:require\s+)?" + re.escape(module) + r"\s+(v[^\s]+)", text)
    if len(found) != 1:
        raise ValueError(f"expected one requirement for {module}")
    return found[0]


def project_files(root):
    result = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"], cwd=root, capture_output=True)
    if result.returncode == 0:
        return [Path(p) for p in result.stdout.decode().split("\0") if p
                and not any(x in Path(p).parts for x in [".git", ".review", "vendor", "node_modules"])]
    return [p.relative_to(root) for p in root.rglob("*") if p.is_file()
            and not any(x in p.relative_to(root).parts for x in [".git", ".review", "vendor", "node_modules"])]


def copies_shared_vendor(text):
    """Find root-context COPY/ADD consumers, including JSON and continued forms.

    Stage copies do not consume repository module inputs. The fixture's own
    small context is already managed separately; root-context consumers must
    join SHARED_VENDOR_BUILDS so CI builds them from this same inventory.
    """
    logical = re.sub(r"\\\r?\n", " ", text)
    for line in logical.splitlines():
        match = re.match(r"^\s*(?:COPY|ADD)\s+(.+)$", line, re.I)
        if not match:
            continue
        args = match[1].strip()
        flags = []
        while args.startswith("--"):
            parts = args.split(None, 1)
            flags.append(parts[0])
            args = parts[1] if len(parts) == 2 else ""
        if any(flag.lower().startswith("--from=") for flag in flags):
            continue
        values = json.loads(args) if args.startswith("[") else shlex.split(args, comments=True)
        if not isinstance(values, list) or any(not isinstance(v, str) for v in values):
            raise ValueError("invalid COPY/ADD source list")
        for source in values[:-1]:
            source = source.removeprefix("./").lstrip("/")
            if source.rstrip("/") == "cicd/common/reflect-echo" or source.startswith("cicd/common/reflect-echo/"):
                return True
    return False


def check(root, pins):
    errors = []
    vendor = (root / "cicd/common/reflect-echo/vendor/modules.txt").read_text()
    net_floor = re.search(r"(?m)^# golang.org/x/net [^\n]+\n## explicit; go (\d+\.\d+\.\d+)$", vendor)
    if not net_floor:
        errors.append("missing vendored x/net Go minimum metadata")
    for path in RECIPES:
        text = (root / path).read_text()
        try:
            if render_recipe(path, text, pins) != text:
                errors.append(f"stale generated pins: {path}")
        except ValueError as error:
            errors.append(f"{path}: {error}")
    for path in MODULES:
        text = (root / path).read_text()
        if requirement(text, "golang.org/x/net") != pins["x_net"]:
            errors.append(f"stale x/net requirement: {path}")
        floor = re.search(r"(?m)^go (\d+\.\d+(?:\.\d+)?)$", text)
        if not floor:
            errors.append(f"missing Go version: {path}")
        else:
            version = tuple(map(int, (floor[1] + ".0").split(".")[:3]))
            if tuple(map(int, pins["go"].split("."))) < version:
                errors.append(f"pinned compiler is below {path}'s Go requirement")
            if net_floor and version < tuple(map(int, net_floor[1].split("."))):
                errors.append(f"{path}'s Go requirement is below vendored x/net's minimum")
    root_mod = (root / "go.mod").read_text()
    for module, version in [("google.golang.org/grpc", pins["grpc"]),
                            ("github.com/osrg/gobgp/v3", pins["gobgp"]["default"])]:
        if requirement(root_mod, module) != version:
            errors.append(f"stale root requirement: {module}")
    if not re.search(r"(?m)^# golang.org/x/net " + re.escape(pins["x_net"]) + "$", vendor):
        errors.append("stale reflect-echo vendor metadata")
    # A new independently pinned module/recipe must join the managed inventory.
    for path in project_files(root):
        name = path.as_posix()
        if path.name.startswith("Dockerfile") and name not in RECIPES:
            text = (root / path).read_text()
            if copies_shared_vendor(text):
                errors.append(f"unmanaged shared-vendor recipe: {name}")
            if re.search(r"(?:golang.org/x/net|google.golang.org/grpc|osrg/gobgp.git)(?:@|\b)", text):
                errors.append(f"unmanaged Go dependency recipe: {name}")
        if path.name == "go.mod" and name not in MODULES:
            if re.search(r"(?m)^\s*(?:require\s+)?golang\.org/x/net\s+v", (root / path).read_text()):
                errors.append(f"unmanaged x/net module: {name}")
    return errors


def verify_vendor(root):
    fixture = root / "cicd/common/reflect-echo"
    with tempfile.TemporaryDirectory(prefix="go-vendor-replay-") as directory:
        replay = Path(directory)
        for path in [fixture / "go.mod", fixture / "go.sum", *fixture.rglob("*.go")]:
            relative = path.relative_to(fixture)
            if "vendor" in relative.parts:
                continue
            target = replay / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, target)
        subprocess.run(["go", "mod", "vendor"], cwd=replay, env=dict(os.environ, GOWORK="off"), check=True)
        def content(path):
            return {str(f.relative_to(path)): f.read_bytes() for f in path.rglob("*") if f.is_file()}
        if content(replay / "vendor") != content(fixture / "vendor"):
            raise ValueError("reflect-echo vendor differs from a clean go mod vendor replay")


def update(root, pins):
    env = dict(os.environ, GOWORK="off")
    commands = [(root, ["go", "get", "golang.org/x/net@" + pins["x_net"],
                        "google.golang.org/grpc@" + pins["grpc"],
                        "github.com/osrg/gobgp/v3@" + pins["gobgp"]["default"]]),
                (root, ["go", "mod", "tidy"])]
    fixture = root / "cicd/common/reflect-echo"
    commands += [(fixture, ["go", "get", "golang.org/x/net@" + pins["x_net"]]),
                 (fixture, ["go", "mod", "tidy"]), (fixture, ["go", "mod", "vendor"])]
    for cwd, cmd in commands:
        subprocess.run(cmd, cwd=cwd, env=env, check=True)
    for path in RECIPES:
        target = root / path
        target.write_text(render_recipe(path, target.read_text(), pins))
    (root / MANIFEST).write_text(json.dumps(pins, indent=2) + "\n")
    errors = check(root, pins)
    if errors:
        raise ValueError("\n".join(errors))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--list-shared-vendor-builds", action="store_true",
                      help="print CI profile and root-context Dockerfile as TSV")
    mode.add_argument("--print-go-version", action="store_true")
    mode.add_argument("--print-govulncheck-version", action="store_true")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--x-net", help="new x/net version (with --write)")
    parser.add_argument("--grpc", help="new common gRPC version (with --write)")
    parser.add_argument("--go-version", help="new complete compiler version (with --write)")
    parser.add_argument("--verify-vendor", action="store_true", help="replay vendor in a temporary directory (requires Go)")
    args = parser.parse_args()
    try:
        pins = json.loads((args.root / MANIFEST).read_text())
        if (args.x_net or args.grpc or args.go_version) and not args.write:
            raise ValueError("version overrides require --write")
        if args.x_net:
            pins["x_net"] = args.x_net
        if args.grpc:
            pins["grpc"] = args.grpc
        if args.go_version:
            pins["go"] = args.go_version
        validate(pins)
        if args.print_go_version or args.print_govulncheck_version:
            print(pins["go"] if args.print_go_version else pins["govulncheck"])
            return 0
        if args.write:
            update(args.root, pins)
        errors = check(args.root, pins)
        if errors:
            raise ValueError("\n".join(errors))
        if args.verify_vendor:
            verify_vendor(args.root)
        if args.list_shared_vendor_builds:
            for recipe, profile in SHARED_VENDOR_BUILDS.items():
                print(profile + "\t" + recipe)
            return 0
        print("PASS: Go module, vendor and Dockerfile pins match " + MANIFEST)
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(error, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
