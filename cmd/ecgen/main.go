// ecgen compiles the engine-contract trust artifacts into build-time
// registries: the Go profile registry (pkg/enginecontract/
// zz_generated_registry.go) and the C P/D engine-ID header
// (loxilb-ebpf/common/sockproxy_pd_ids.h). One manifest feeds both sides
// so the Go/C IDs cannot drift.
//
// Usage (from the repository root):
//
//	go run ./cmd/ecgen           # regenerate both artifacts in place
//	go run ./cmd/ecgen -check    # verify committed artifacts match (CI)
//
// Output is deterministic: identical inputs produce byte-identical
// artifacts (no timestamps, sorted iteration), so CI can regenerate and
// fail on any diff.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"

	"github.com/loxilb-io/loxilb/pkg/enginecontract/schema"
)

func sha256Hex(b []byte) string {
	sum := sha256.Sum256(b)
	return "sha256:" + hex.EncodeToString(sum[:])
}

// profileDigest computes a profile's canonical content digest: JSON with
// the struct's fixed field order. Contract references resolve to this
// digest; two builds agree on a profile exactly when these bytes agree.
func profileDigest(p *schema.Profile) string {
	b, err := json.Marshal(p)
	if err != nil {
		panic(err) // struct marshal of plain fields cannot fail
	}
	return sha256Hex(b)
}

func generateGo(m *schema.ContractsManifest, manifestDigest, catalogDigest string) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by ecgen from engine-contracts/contracts.yaml. DO NOT EDIT.

package enginecontract

import "github.com/loxilb-io/loxilb/pkg/enginecontract/schema"

// Registry identity constants. ManifestDigest and SupportCatalogDigest
// cover the exact artifact bytes this build compiled in; peers compare
// them during the HA capability exchange.
const (
	SchemaVersion        = %q
	Generation    uint64 = %d
	ManifestDigest       = %q
	SupportCatalogDigest = %q
)

// EngineWireIDs is the ABI-frozen numeric kv_engine_type encoding shared
// with the eBPF/C data plane (sockproxy_pd_ids.h is generated from the
// same manifest).
var EngineWireIDs = map[string]uint8{
`, m.SchemaVersion, m.Generation, manifestDigest, catalogDigest)
	engines := make([]string, 0, len(m.EngineIDs))
	for e := range m.EngineIDs {
		engines = append(engines, e)
	}
	sort.Strings(engines)
	for _, e := range engines {
		fmt.Fprintf(&b, "\t%q: %d,\n", e, m.EngineIDs[e])
	}
	b.WriteString("}\n\n// ProfileDigests maps profile ID to its canonical content digest.\nvar ProfileDigests = map[string]string{\n")
	for _, id := range m.SortedProfileIDs() {
		p, _ := m.ProfileByID(id)
		fmt.Fprintf(&b, "\t%q: %q,\n", id, profileDigest(p))
	}
	b.WriteString("}\n\n// Profiles is the compiled profile table, sorted by ID.\nvar Profiles = []schema.Profile{\n")
	for _, id := range m.SortedProfileIDs() {
		p, _ := m.ProfileByID(id)
		fmt.Fprintf(&b, "\t{\n\t\tID: %q,\n\t\tEngine: %q,\n", p.ID, p.Engine)
		if p.FamilyDefault {
			b.WriteString("\t\tFamilyDefault: true,\n")
		}
		fmt.Fprintf(&b, "\t\tVersions: schema.VersionSelector{Scheme: %q", p.Versions.Scheme)
		if p.Versions.MinInclusive != "" {
			fmt.Fprintf(&b, ", MinInclusive: %q, MaxInclusive: %q", p.Versions.MinInclusive, p.Versions.MaxInclusive)
		}
		if p.Versions.Exact != "" {
			fmt.Fprintf(&b, ", Exact: %q", p.Versions.Exact)
		}
		fmt.Fprintf(&b, "},\n\t\tTransport: %q,\n\t\tWireSchema: %q,\n\t\tHashBinding: %q,\n\t\tPDDialect: %q,\n\t\tProbe: %q,\n",
			p.Transport, p.WireSchema, p.HashBinding, p.PDDialect, p.Probe)
		caps := make([]string, 0, len(p.Capabilities))
		for c := range p.Capabilities {
			caps = append(caps, c)
		}
		sort.Strings(caps)
		b.WriteString("\t\tCapabilities: map[string]string{")
		for i, c := range caps {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q: %q", c, p.Capabilities[c])
		}
		b.WriteString("},\n\t},\n")
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func generateCHeader(m *schema.ContractsManifest) []byte {
	var b bytes.Buffer
	b.WriteString(`/* Code generated by ecgen from engine-contracts/contracts.yaml. DO NOT EDIT.
 *
 * P/D orchestration engine wire IDs (proxy_epval_t.pd_engine and the wire
 * kv_engine_type encoding). Values are ABI-frozen: they cross the Go->C
 * boundary as numbers and must never be renumbered. Adding an engine =
 * manifest change + regeneration, never a hand edit here. An ID absent
 * from this header is unknown to the data plane and MUST fail closed
 * (no default-to-vLLM fallback).
 */
#ifndef __SOCKPROXY_PD_IDS_H__
#define __SOCKPROXY_PD_IDS_H__

`)
	type eng struct {
		name string
		id   uint8
	}
	engines := make([]eng, 0, len(m.EngineIDs))
	for e, id := range m.EngineIDs {
		engines = append(engines, eng{e, id})
	}
	sort.Slice(engines, func(i, j int) bool { return engines[i].id < engines[j].id })
	maxID := uint8(0)
	for _, e := range engines {
		fmt.Fprintf(&b, "#define PD_ENGINE_%s %d\n", upperASCII(e.name), e.id)
		if e.id > maxID {
			maxID = e.id
		}
	}
	fmt.Fprintf(&b, "\n/* Highest generated engine ID; anything above is unknown. */\n#define PD_ENGINE_ID_MAX %d\n\n#endif /* __SOCKPROXY_PD_IDS_H__ */\n", maxID)
	return b.Bytes()
}

func upperASCII(s string) string {
	out := []byte(s)
	for i := range out {
		if out[i] >= 'a' && out[i] <= 'z' {
			out[i] -= 'a' - 'A'
		}
	}
	return string(out)
}

func writeOrCheck(path string, content []byte, check bool) error {
	if check {
		got, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("%s: %w (run `go run ./cmd/ecgen`)", path, err)
		}
		if !bytes.Equal(got, content) {
			return fmt.Errorf("%s is stale — run `go run ./cmd/ecgen` and commit the diff", path)
		}
		return nil
	}
	return os.WriteFile(path, content, 0o644)
}

func run() error {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "verify committed artifacts instead of writing")
	flag.Parse()

	cb, err := os.ReadFile(filepath.Join(*root, "engine-contracts", "contracts.yaml"))
	if err != nil {
		return err
	}
	m, err := schema.ParseContracts(cb)
	if err != nil {
		return err
	}
	sb, err := os.ReadFile(filepath.Join(*root, "engine-contracts", "support-catalog.yaml"))
	if err != nil {
		return err
	}
	if _, err := schema.ParseCatalog(sb, m); err != nil {
		return err
	}
	ob, err := os.ReadFile(filepath.Join(*root, "engine-contracts", "observed-releases.json"))
	if err != nil {
		return err
	}
	if _, err := schema.ParseObserved(ob); err != nil {
		return err
	}

	goOut := generateGo(m, sha256Hex(cb), sha256Hex(sb))
	if err := writeOrCheck(filepath.Join(*root, "pkg", "enginecontract", "zz_generated_registry.go"), goOut, *check); err != nil {
		return err
	}
	cOut := generateCHeader(m)
	if err := writeOrCheck(filepath.Join(*root, "loxilb-ebpf", "common", "sockproxy_pd_ids.h"), cOut, *check); err != nil {
		return err
	}
	if *check {
		fmt.Println("ecgen: committed artifacts match the manifest")
	} else {
		fmt.Println("ecgen: regenerated zz_generated_registry.go and sockproxy_pd_ids.h")
	}
	return nil
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "ecgen:", err)
		os.Exit(1)
	}
}
