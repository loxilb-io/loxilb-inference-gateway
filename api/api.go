// RunAPIServer - routine to start API server
func RunAPIServer() {

	// Stack trace logger
	defer func() {
		if e := recover(); e != nil {
			tk.LogIt(tk.LogCritical, "%s: %s", e, debug.Stack())
		}
		handler.ApiHooks.NetHandlePanic()
		os.Exit(1)
	}()

	if ApiShutOk == nil {
		ApiShutOk = make(chan bool)
	}

	swaggerSpec, err := loads.Embedded(restapi.SwaggerJSON, restapi.FlatSwaggerJSON)
	if err != nil {
		log.Fatalln(err)
	}

	api := operations.NewLoxilbRestAPIAPI(swaggerSpec)
	server := restapi.NewServer(api)
	defer server.Shutdown()

	parser := flags.NewParser(server, flags.Default)
	parser.ShortDescription = "Loxilb Rest API"
	parser.LongDescription = "Loxilb REST API for Baremetal Scenarios"
	server.ConfigureFlags()
	for _, optsGroup := range api.CommandLineOptionsGroups {
		_, err := parser.AddGroup(optsGroup.ShortDescription, optsGroup.LongDescription, optsGroup.Options)
		if err != nil {
			log.Fatalln(err)
		}
	}
	if _, err := parser.Parse(); err != nil {
		code := 1
		if fe, ok := err.(*flags.Error); ok {
			if fe.Type == flags.ErrHelp {
				code = 0
			}
		}
		os.Exit(code)
	}

	server.ConfigureAPI()

	// The audit trail is prepared before any socket binds: every management
	// change is recorded ahead of the handler, so a directory that cannot
	// be written is known now rather than on the first mutating call. A
	// deployment that mandates auditing refuses to start; every other one
	// starts and the gate refuses the audited calls instead, which is the
	// same failure made visible at request time.
	auditCtx := api.Context()
	handler.SetAuditRouteLookup(swaggerSpec.BasePath(), func(r *http.Request) (string, bool) {
		route, ok := auditCtx.LookupRoute(r)
		if !ok || route == nil {
			return "", false
		}
		return route.PathPattern, true
	})
	auditW, err := audit.New(audit.Config{
		Dir:        options.Opts.AuditDir,
		CreateDir:  true,
		InstanceID: auditInstanceID(),
		Logf: func(format string, args ...interface{}) {
			tk.LogIt(tk.LogError, format+"\n", args...)
		},
		ConfigGeneration: snapshot.ConfigGeneration,
	})
	if err != nil {
		tk.LogIt(tk.LogCritical, "api: audit trail unavailable: %s\n", err.Error())
		if options.Opts.AuditRequired {
			log.Fatalln(err)
		}
		tk.LogIt(tk.LogCritical, "api: audited management calls will be refused until the audit directory is usable (--audit-dir=%s)\n",
			options.Opts.AuditDir)
	} else {
		auditW.Start()
		handler.SetAuditWriter(auditW)
		tk.LogIt(tk.LogInfo, "api: audit trail at %s (boot %s)\n", options.Opts.AuditDir, auditW.BootID())
	}

	// The management-listener profile decides where the API may listen and
	// which listeners exist at all. A failed plan is fatal before any socket
	// binds: every failure means a security precondition of the requested
	// profile does not hold, and serving anyway would expose an interface
	// the profile promises is closed.
	plan, err := options.MgmtListenPlan()
	if err != nil {
		tk.LogIt(tk.LogCritical, "api: %s\n", err.Error())
		log.Fatalln(err)
	}
	tk.LogIt(tk.LogInfo, "api: mgmt-profile %s: http=%v https=%v\n",
		options.Opts.MgmtProfile, plan.HTTP, plan.HTTPS)

	// Whether /metrics demands a bearer is decided here, once, for the same
	// reason and at the same moment as the listener plan: an operator asking
	// for a combination the profile forbids must be told before a socket
	// binds, not after a scraper has already read the tenant roster.
	metricsAuth, err := options.MetricsAuthPlan()
	if err != nil {
		tk.LogIt(tk.LogCritical, "api: %s\n", err.Error())
		log.Fatalln(err)
	}
	handler.SetMetricsAuthRequired(metricsAuth)
	tk.LogIt(tk.LogInfo, "api: /metrics requires authentication: %v (--metrics-auth=%s)\n",
		metricsAuth, options.Opts.MetricsAuth)

	// API server host list
	server.Host = plan.Host
	server.Port = options.Opts.Port

	// HTTPs List
	if options.Opts.TLS {
		server.TLSHost = plan.TLSHost
		server.TLSPort = options.Opts.TLSPort

		server.TLSCertificateKey = options.Opts.TLSCertificateKey
		server.TLSCertificate = options.Opts.TLSCertificate
	}

	// Only the non-legacy profiles take ownership of the enabled-listener
	// set; under legacy the server keeps its historical defaulting so the
	// pre-profile behavior stays untouched.
	if plan.Explicit {
		server.EnabledListeners = nil
		if plan.HTTP {
			server.EnabledListeners = append(server.EnabledListeners, "http")
		}
		if plan.HTTPS {
			server.EnabledListeners = append(server.EnabledListeners, "https")
		}
	}

	api.ServerShutdown = func() {
		waitApiServerShutOk()
		closeCtx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		if err := handler.CloseAuditWriter(closeCtx); err != nil {
			tk.LogIt(tk.LogError, "api: audit trail close: %s\n", err.Error())
		}
		os.Exit(0)
	}
	ApiReady = true
	EmbeddedSwaggerInit()

	if err := server.Serve(); err != nil {
		log.Fatalln(err)
	}

}

// auditInstanceID is the identity written into every audit record. It is
// the same LOXILB_INSTANCE_ID the trace exporter reports, so the two
// pipelines name one deployment the same way; the package default applies
// when it is unset.
func auditInstanceID() string {
	if v := os.Getenv("LOXILB_INSTANCE_ID"); v != "" {
		return v
	}
	return audit.DefaultInstanceID
}
