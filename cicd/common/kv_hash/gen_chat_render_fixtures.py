#!/usr/bin/env python3
"""Generate the chat-template render-parity goldens (kv_chat_render_parity.json).

Offline CI oracle for the gateway's in-process template executor: for each
profile-pinned model, load the PINNED tokenizer snapshot with HF transformers,
assert its chat_template bytes hash to the banked template artifact digest,
then record apply_chat_template output (rendered string + token ids,
add_generation_prompt=True) for a fixed battery of role/content message cases.

The gateway executor must reproduce `rendered` byte-identically from the SAME
banked template artifact, and its Encode(rendered, add_special_tokens=False)
must equal `templated_ids` (the tokenize=True output) — the same invariant the
P7 Qwen2.5 fixture proved live (encode_rendered_matches_templated).

Usage:
  gen_chat_render_fixtures.py <out.json> <slug>=<snapshot_dir>[,<slug>=<dir>...] \
      --templates <banked_templates_root>

<slug> is the gateway model slug ("/" -> "__"). <snapshot_dir> is the pinned
HF snapshot directory (contains tokenizer_config.json). The banked templates
root holds <slug>/chat_template.jinja; a digest mismatch between the snapshot's
chat_template and the banked artifact is a hard error — the oracle must never
generate goldens for bytes the gateway will not serve.
"""
import argparse
import hashlib
import json
import sys

from transformers import AutoTokenizer

# One battery for every model: plain role/content strings only (the gateway
# refuses tools/multimodal/template-kwargs requests on strict rules, so the
# executor's reachable domain is exactly this shape). Cases deliberately
# exercise: default-system injection (qwen25/exaone) vs no-default (qwen3),
# explicit system, multi-turn assistant paths (qwen3 last_query_index +
# think-strip), llama's `| trim` filter, unicode, and whitespace edges.
CASES = {
    "user-only": [
        {"role": "user", "content": "What is the capital of France?"},
    ],
    "system-user": [
        {"role": "system", "content": "You are a terse assistant. Answer in one word."},
        {"role": "user", "content": "What is the capital of France?"},
    ],
    "multi-turn": [
        {"role": "system", "content": "You are a helpful assistant."},
        {"role": "user", "content": "Name a prime number."},
        {"role": "assistant", "content": "Seven."},
        {"role": "user", "content": "And the next one after it?"},
    ],
    "assistant-think": [
        {"role": "user", "content": "Is 9 prime?"},
        {"role": "assistant", "content": "<think>\n9 = 3*3, not prime.\n</think>\n\nNo, 9 is composite."},
        {"role": "user", "content": "And 11?"},
    ],
    "whitespace-edges": [
        {"role": "user", "content": "  leading and trailing spaces  "},
        {"role": "assistant", "content": "\nnewline-wrapped reply\n"},
        {"role": "user", "content": "final\nmulti-line\nquestion"},
    ],
    "unicode-mix": [
        {"role": "user", "content": "Tokenizer parity check: café naïve 안녕하세요 你好 こんにちは."},
    ],
}


def sha256_hex(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("models", help="comma-separated <slug>=<snapshot_dir> pairs")
    ap.add_argument("--templates", required=True, help="banked templates root")
    args = ap.parse_args()

    import transformers

    doc = {
        "_note": (
            "Chat-template render-parity goldens generated by "
            "gen_chat_render_fixtures.py (HF transformers oracle, offline). "
            "The gateway's template executor must reproduce `rendered` "
            "byte-identically from the banked template artifact, and encoding "
            "the render with add_special_tokens=False must equal "
            "`templated_ids`."
        ),
        "transformers_version": transformers.__version__,
        "models": {},
    }

    for pair in args.models.split(","):
        slug, snap = pair.split("=", 1)
        banked_path = f"{args.templates}/{slug}/chat_template.jinja"
        banked = open(banked_path, "rb").read()
        banked_sha = sha256_hex(banked)

        # trust_remote_code: EXAONE's pinned snapshot ships a custom tokenizer
        # class. The oracle runs offline over audited pinned bytes only.
        tok = AutoTokenizer.from_pretrained(snap, trust_remote_code=True)
        tpl = tok.chat_template
        if tpl is None:
            print(f"{slug}: snapshot has no chat_template", file=sys.stderr)
            return 1
        live_sha = sha256_hex(tpl.encode("utf-8"))
        if live_sha != banked_sha:
            print(
                f"{slug}: snapshot chat_template sha {live_sha} != banked artifact {banked_sha}",
                file=sys.stderr,
            )
            return 1

        entry = {
            "template_sha256": banked_sha,
            "bos_token": tok.bos_token,
            "eos_token": tok.eos_token,
            "cases": {},
        }
        for name, msgs in CASES.items():
            rendered = tok.apply_chat_template(
                msgs, tokenize=False, add_generation_prompt=True
            )
            templated_ids = tok.apply_chat_template(
                msgs, tokenize=True, add_generation_prompt=True
            )
            # transformers 5.x returns a BatchEncoding here; 4.x a plain list.
            if not isinstance(templated_ids, list):
                templated_ids = list(templated_ids["input_ids"])
            if templated_ids and isinstance(templated_ids[0], list):
                templated_ids = templated_ids[0]
            encoded = tok.encode(rendered, add_special_tokens=False)
            entry["cases"][name] = {
                "messages": msgs,
                "rendered": rendered,
                "rendered_sha256": sha256_hex(rendered.encode("utf-8")),
                "templated_ids": templated_ids,
                "encode_rendered_matches_templated": encoded == templated_ids,
            }
            if encoded != templated_ids:
                print(f"{slug}/{name}: encode(render) != templated_ids", file=sys.stderr)
        doc["models"][slug] = entry
        print(f"{slug}: {len(CASES)} cases, template {banked_sha[:12]}…")

    with open(args.out, "w") as f:
        json.dump(doc, f, ensure_ascii=False, indent=1)
        f.write("\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
